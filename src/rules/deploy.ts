type Tx = Parameters<Parameters<typeof txDb.transaction>[0]>[0];

/** Writes the audit entry for a deployment step, inside the caller's transaction. */
async function auditInTx(
  tx: Tx,
  entry: {
    actor: string;
    action: string;
    entityType: string;
    entityId: string;
    details?: unknown;
  },
): Promise<void> {
  await tx.insert(auditLog).values({
    actor: entry.actor,
    action: entry.action,
    entityType: entry.entityType,
    entityId: entry.entityId,
    details: (entry.details ?? null) as never,
  });
}

async function loadVersion(tx: Tx, versionId: string) {
  const [version] = await tx
    .select({
      id: ruleVersions.id,
      ruleId: ruleVersions.ruleId,
      version: ruleVersions.version,
      status: ruleVersions.status,
      jsonLogic: ruleVersions.jsonLogic,
      rolloutPercent: ruleVersions.rolloutPercent,
      submittedBy: ruleVersions.submittedBy,
    })
    .from(ruleVersions)
    .where(eq(ruleVersions.id, versionId))
    .limit(1);

  if (!version) {
    throw new DeploymentStateError(`Rule version ${versionId} does not exist.`);
  }
  return version;
}

/* -------------------------------------------------------------------------- */
/* 1. Start shadow                                                            */
/* -------------------------------------------------------------------------- */

export interface StartShadowResult {
  ruleVersionId: string;
  ruleCode: string;
  version: number;
  status: "shadow";
}

/**
 * Moves an approved version into shadow.
 *
 * Requires a recorded approval by someone other than the submitter: the
 * maker-checker rule is re-verified here rather than assumed from the status,
 * because status alone could be set by a future code path that forgot.
 */
export async function startShadow(
  versionId: string,
  actor: DeployActor,
): Promise<StartShadowResult> {
  assertOpsActor(actor, "Starting a shadow run");

  return txDb.transaction(async (tx) => {
    const version = await loadVersion(tx, versionId);

    if (version.status !== "approved") {
      throw new DeploymentStateError(
        `Only an approved version can enter shadow; this one is ${version.status}.`,
      );
    }

    const [approval] = await tx
      .select({
        makerId: sql<string>`maker_id`,
        checkerId: sql<string>`checker_id`,
      })
      .from(sql`approvals`)
      .where(
        sql`rule_version_id = ${versionId} and decision = 'approved' and checker_id <> maker_id`,
      )
      .limit(1);

    if (!approval) {
      throw new DeploymentStateError(
        "This version has no approval recorded by someone other than its submitter.",
      );
    }

    const [rule] = await tx
      .select({ code: rules.code })
      .from(rules)
      .where(eq(rules.id, version.ruleId))
      .limit(1);

    await tx
      .update(ruleVersions)
      .set({
        status: "shadow",
        shadowStartedAt: new Date(),
        rolloutPercent: 0,
      })
      .where(
        and(eq(ruleVersions.id, versionId), eq(ruleVersions.status, "approved")),
      );

    await auditInTx(tx, {
      actor: `user:${actor.email}`,
      action: "rule_version.shadow_started",
      entityType: "rule_versions",
      entityId: versionId,
      details: {
        rule_code: rule?.code ?? null,
        version: version.version,
        maker_id: approval.makerId,
        checker_id: approval.checkerId,
      },
    });

    return {
      ruleVersionId: versionId,
      ruleCode: rule?.code ?? "",
      version: version.version,
      status: "shadow" as const,
    };
  });
}

/* -------------------------------------------------------------------------- */
/* 2. Shadow comparison                                                       */
/* -------------------------------------------------------------------------- */

export interface ShadowComparison {
  shadowRunId: string;
  ruleVersionId: string;
  baselineVersionId: string | null;
  txnsEvaluated: number;
  liveAlerts: number;
  shadowAlerts: number;
  alertsOnlyLive: number;
  alertsOnlyShadow: number;
  /** Null when the live rule raised nothing, so a ratio is undefined. */
  alertRateChangePct: number | null;
  simulated: boolean;
  sampleOnlyShadow: string[];
  sampleOnlyLive: string[];
}

/** Batches used when walking transactions. */
const SHADOW_BATCH = 5_000;

/**
 * Runs the live rule and the shadow rule over the same transactions and
 * records the difference.
 *
 * The shadow rule's output is counted and nothing else: no alert is raised, no
 * customer record is touched, and `rules.current_version_id` is not read or
 * written. A shadow run is an observation, never an effect.
 */
export async function runShadowComparison(
  versionId: string,
  options: { simulate: boolean },
  actor: DeployActor,
): Promise<ShadowComparison> {
  assertOpsActor(actor, "Running a shadow comparison");

  // Generating the synthetic day happens before the transaction: it is an
  // ordinary insert of test data, and holding a transaction open across 2,000
  // generated rows buys nothing.
  let generated = 0;
  if (options.simulate) {
    generated = await generateSimulatedDay(versionId);
  }

  return txDb.transaction(async (tx) => {
    const version = await loadVersion(tx, versionId);

    if (version.status !== "shadow") {
      throw new DeploymentStateError(
        `Only a version in shadow can be compared; this one is ${version.status}.`,
      );
    }

    const [rule] = await tx
      .select({ code: rules.code, currentVersionId: rules.currentVersionId })
      .from(rules)
      .where(eq(rules.id, version.ruleId))
      .limit(1);

    const baselineVersionId = rule?.currentVersionId ?? null;
    const baselineLogic = baselineVersionId
      ? (
          await tx
            .select({ jsonLogic: ruleVersions.jsonLogic })
            .from(ruleVersions)
            .where(eq(ruleVersions.id, baselineVersionId))
            .limit(1)
        )[0]?.jsonLogic
      : undefined;

    const evaluateLive = baselineLogic ? compileRule(baselineLogic) : NEVER_FIRES;
    const evaluateShadow = compileRule(version.jsonLogic);

    const since = new Date(
      Date.now() - SHADOW_WINDOW_DAYS * 24 * 60 * 60 * 1000,
    );

    let txnsEvaluated = 0;
    let liveAlerts = 0;
    let shadowAlerts = 0;
    let alertsOnlyLive = 0;
    let alertsOnlyShadow = 0;
    const sampleOnlyShadow: string[] = [];
    const sampleOnlyLive: string[] = [];

    let cursor: string | null = null;
    for (;;) {
      const batch = await tx
        .select({
          id: transactions.id,
          customerId: transactions.customerId,
          amount: transactions.amount,
          currency: transactions.currency,
          type: transactions.type,
          channel: transactions.channel,
          branch: transactions.branch,
          country: transactions.country,
        })
        .from(transactions)
        .where(
          and(
            gte(transactions.timestamp, since),
            cursor ? sql`${transactions.id} > ${cursor}` : undefined,
          ),
        )
        .orderBy(transactions.id)
        .limit(SHADOW_BATCH);

      if (batch.length === 0) break;

      for (const txn of batch) {
        txnsEvaluated += 1;
        const live = evaluateLive(txn);
        const shadow = evaluateShadow(txn);

        if (live) liveAlerts += 1;
        if (shadow) shadowAlerts += 1;

        if (shadow && !live) {
          alertsOnlyShadow += 1;
          if (sampleOnlyShadow.length < 10) sampleOnlyShadow.push(txn.id);
        } else if (live && !shadow) {
          alertsOnlyLive += 1;
          if (sampleOnlyLive.length < 10) sampleOnlyLive.push(txn.id);
        }
      }

      cursor = batch[batch.length - 1].id;
      if (batch.length < SHADOW_BATCH) break;
    }

    const alertRateChangePct =
      liveAlerts > 0
        ? ((shadowAlerts - liveAlerts) / liveAlerts) * 100
        : null;

    const resultJson = {
      simulated: options.simulate,
      generated_transactions: generated,
      window_days: SHADOW_WINDOW_DAYS,
      sample_only_shadow: sampleOnlyShadow,
      sample_only_live: sampleOnlyLive,
      ran_at: new Date().toISOString(),
    };

    const [run] = await tx
      .insert(shadowRuns)
      .values({
        ruleVersionId: versionId,
        baselineVersionId,
        txnsEvaluated,
        liveAlerts,
        shadowAlerts,
        alertsOnlyLive,
        alertsOnlyShadow,
        alertRateChangePct:
          alertRateChangePct === null ? null : alertRateChangePct.toFixed(2),
        resultJson,
        createdBy: actor.id,
      })
      .returning({ id: shadowRuns.id });

    await auditInTx(tx, {
      actor: `user:${actor.email}`,
      action: "rule_version.shadow_compared",
      entityType: "rule_versions",
      entityId: versionId,
      details: {
        shadow_run_id: run.id,
        rule_code: rule?.code ?? null,
        simulated: options.simulate,
        generated_transactions: generated,
        txns_evaluated: txnsEvaluated,
        live_alerts: liveAlerts,
        shadow_alerts: shadowAlerts,
        alerts_only_live: alertsOnlyLive,
        alerts_only_shadow: alertsOnlyShadow,
        alert_rate_change_pct: alertRateChangePct,
      },
    });

    return {
      shadowRunId: run.id,
      ruleVersionId: versionId,
      baselineVersionId,
      txnsEvaluated,
      liveAlerts,
      shadowAlerts,
      alertsOnlyLive,
      alertsOnlyShadow,
      alertRateChangePct,
      simulated: options.simulate,
      sampleOnlyShadow,
      sampleOnlyLive,
    };
  });
}

/**
 * Inserts a synthetic day of transactions for a simulated comparison.
 *
 * Seeded from the version id so one version's simulated day is reproducible,
 * and deliberately salted with amounts either side of the thresholds the rule
 * cares about, so the comparison has something to show.
 */
async function generateSimulatedDay(versionId: string): Promise<number> {
  const { faker } = await import("@faker-js/faker");

  // Same version, same day: a stable seed keeps a re-run comparable.
  const seed = Number.parseInt(versionId.replace(/\D/g, "").slice(0, 9) || "1", 10);
  faker.seed(seed);

  const now = Date.now();
  const dayStart = new Date(now - 24 * 60 * 60 * 1000);

  const BRANCHES = [
    "Mumbai - Fort",
    "Delhi - Connaught Place",
    "Bengaluru - Koramangala",
    "Chennai - T Nagar",
    "Pune - Kothrud",
  ];
  const FOREIGN = ["AE", "US", "GB", "SG"];
  const TYPES = [
    { value: "cash_deposit" as const, weight: 14 },
    { value: "cash_withdrawal" as const, weight: 16 },
    { value: "transfer" as const, weight: 20 },
    { value: "upi" as const, weight: 34 },
    { value: "card" as const, weight: 14 },
    { value: "loan_disbursal" as const, weight: 2 },
  ];
  const CHANNELS: Record<string, Array<NewTransaction["channel"]>> = {
    cash_deposit: ["branch", "atm"],
    cash_withdrawal: ["atm", "branch"],
    transfer: ["internet", "mobile", "branch"],
    upi: ["mobile"],
    card: ["internet", "mobile"],
    loan_disbursal: ["branch"],
  };

  /** Amounts straddling the thresholds the seeded rules use. */
  const PROBE_AMOUNTS = [
    499_999, 500_000, 500_001, 999_999, 1_000_000, 1_000_001, 199_999, 200_000,
    200_001, 99_999, 100_000, 100_001,
  ];

  const rows: NewTransaction[] = [];
  for (let i = 0; i < SIMULATED_TXN_COUNT; i += 1) {
    const type = faker.helpers.weightedArrayElement(TYPES);
    const channel = faker.helpers.arrayElement(CHANNELS[type]);

    // Every fifth row sits on a threshold boundary so a changed threshold
    // always produces a visible difference.
    const amount =
      i % 5 === 0
        ? faker.helpers.arrayElement(PROBE_AMOUNTS)
        : faker.number.int({ min: 100, max: 1_500_000 });

    const foreign = type === "transfer" && i % 7 === 0;

    rows.push({
      id: faker.string.uuid(),
      customerId: `CUST-${String(faker.number.int({ min: 1, max: 2000 })).padStart(6, "0")}`,
      amount: amount.toFixed(2),
      currency: "INR",
      type,
      channel,
      branch:
        channel === "branch" || channel === "atm"
          ? faker.helpers.arrayElement(BRANCHES)
          : null,
      country: foreign ? faker.helpers.arrayElement(FOREIGN) : "IN",
      timestamp: faker.date.between({ from: dayStart, to: new Date(now) }),
    });
  }

  let inserted = 0;
  for (let i = 0; i < rows.length; i += 1_000) {
    const result = await db
      .insert(transactions)
      .values(rows.slice(i, i + 1_000))
      .onConflictDoNothing({ target: transactions.id })
      .returning({ id: transactions.id });
    inserted += result.length;
  }
  return inserted;
}

/* -------------------------------------------------------------------------- */
/* 3. Rollout                                                                 */
/* -------------------------------------------------------------------------- */

export interface SetRolloutResult {
  ruleVersionId: string;
  ruleCode: string;
  version: number;
  percent: number;
  status: "shadow" | "live";
  retiredVersionId: string | null;
}

export interface SetRolloutOptions {
  /**
   * A typed reason acknowledging the alert-rate guardrail. Required only when
   * the latest shadow run breached it.
   */
  guardrailAcknowledgement?: string;
}

/**
 * Widens a shadow version's rollout, and at 100% makes it the live rule.
 *
 * Below 100% the version stays in shadow and only the customers selected by
 * {@link isCustomerInRollout} are on it; everyone else stays on the version in
 * force. At 100% the previous live version is retired and the rule's current
 * version is repointed, which is the moment the change actually takes effect.
 */
export async function setRollout(
  versionId: string,
  percent: number,
  actor: DeployActor,
  options: SetRolloutOptions = {},
): Promise<SetRolloutResult> {
  assertOpsActor(actor, "Changing a rollout");

  if (!ROLLOUT_STAGES.includes(percent as RolloutStage)) {
    throw new DeploymentStateError(
      `Rollout must be one of ${ROLLOUT_STAGES.join(", ")} percent; got ${percent}.`,
    );
  }

  return txDb.transaction(async (tx) => {
    const version = await loadVersion(tx, versionId);

    if (version.status !== "shadow") {
      throw new DeploymentStateError(
        `Only a version in shadow can be rolled out; this one is ${version.status}.`,
      );
    }

    const [latestRun] = await tx
      .select({
        id: shadowRuns.id,
        alertRateChangePct: shadowRuns.alertRateChangePct,
        liveAlerts: shadowRuns.liveAlerts,
        shadowAlerts: shadowRuns.shadowAlerts,
      })
      .from(shadowRuns)
      .where(eq(shadowRuns.ruleVersionId, versionId))
      .orderBy(desc(shadowRuns.createdAt))
      .limit(1);

    if (!latestRun) {
      throw new DeploymentStateError(
        "This version has no shadow run. Run a shadow comparison before rolling it out.",
      );
    }

    // The guardrail. A big jump in alerts is not forbidden — it may be exactly
    // what the regulation demands — but it must be acknowledged in writing by
    // the person doing it, so the audit trail shows someone saw it.
    const change =
      latestRun.alertRateChangePct === null
        ? null
        : Number(latestRun.alertRateChangePct);
    const acknowledgement = options.guardrailAcknowledgement?.trim() ?? "";

    if (change !== null && change > ALERT_RATE_GUARDRAIL_PCT) {
      if (acknowledgement.length < 10) {
        throw new RolloutGuardrailError(
          `The latest shadow run raises alerts by ${change.toFixed(0)}%, above the ${ALERT_RATE_GUARDRAIL_PCT}% guardrail. ` +
            "Confirm with a typed reason of at least 10 characters to proceed.",
          change,
        );
      }
    }

    const [rule] = await tx
      .select({ code: rules.code, currentVersionId: rules.currentVersionId })
      .from(rules)
      .where(eq(rules.id, version.ruleId))
      .limit(1);

    let retiredVersionId: string | null = null;
    let status: "shadow" | "live" = "shadow";
    const now = new Date();

    if (percent === 100) {
      status = "live";

      // Retire whatever was live for this rule. Scoped by rule id, so two
      // rules going live at once cannot retire each other's versions.
      const retired = await tx
        .update(ruleVersions)
        .set({ status: "retired" })
        .where(
          and(
            eq(ruleVersions.ruleId, version.ruleId),
            eq(ruleVersions.status, "live"),
            ne(ruleVersions.id, versionId),
          ),
        )
        .returning({ id: ruleVersions.id });
      retiredVersionId = retired[0]?.id ?? null;

      await tx
        .update(ruleVersions)
        .set({ status: "live", rolloutPercent: 100, liveAt: now })
        .where(eq(ruleVersions.id, versionId));

      await tx
        .update(rules)
        .set({ currentVersionId: versionId })
        .where(eq(rules.id, version.ruleId));
    } else {
      await tx
        .update(ruleVersions)
        .set({ rolloutPercent: percent })
        .where(
          and(eq(ruleVersions.id, versionId), eq(ruleVersions.status, "shadow")),
        );
    }

    await auditInTx(tx, {
      actor: `user:${actor.email}`,
      action:
        percent === 100 ? "rule_version.went_live" : "rule_version.rollout_set",
      entityType: "rule_versions",
      entityId: versionId,
      details: {
        rule_code: rule?.code ?? null,
        version: version.version,
        percent,
        status,
        retired_version_id: retiredVersionId,
        shadow_run_id: latestRun.id,
        alert_rate_change_pct: change,
        guardrail_acknowledgement: acknowledgement || null,
      },
    });

    return {
      ruleVersionId: versionId,
      ruleCode: rule?.code ?? "",
      version: version.version,
      percent,
      status,
      retiredVersionId,
    };
  });
}

