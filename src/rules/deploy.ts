/**
 * Rollout and rollback.
 *
 * This is the only code in the system that may change which rule is in force,
 * and it is reachable by one role: `ops`. Every function here takes the acting
 * user explicitly, checks their role, does its work in a single database
 * transaction, and writes an `audit_log` entry inside that transaction — so a
 * state change and its record either both happen or neither does.
 *
 * **No agent may call any of these.** The pipeline writes drafts and stops;
 * promotion is a human act. {@link assertOpsActor} rejects any actor that is
 * not a signed-in ops user, which includes every `agent:*` actor the
 * orchestrator uses.
 */
import "server-only";

import { and, desc, eq, gte, ne, sql } from "drizzle-orm";
import { createHash } from "node:crypto";

import {
  auditLog,
  rules,
  ruleVersions,
  shadowRuns,
  transactions,
  type NewTransaction,
} from "@/db/schema";
import type { UserRole } from "@/lib/auth";
import { db } from "@/lib/db";
import { txDb } from "@/lib/db/tx";

import { compileRule, NEVER_FIRES } from "./engine";

/* -------------------------------------------------------------------------- */
/* Actor                                                                      */
/* -------------------------------------------------------------------------- */

/** Who is asking. Deliberately not optional anywhere in this module. */
export interface DeployActor {
  id: string;
  email: string;
  role: UserRole;
}

export class DeploymentForbiddenError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "DeploymentForbiddenError";
  }
}

export class DeploymentStateError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "DeploymentStateError";
  }
}

/** Raised when a rollout is blocked by the alert-rate guardrail. */
export class RolloutGuardrailError extends Error {
  constructor(
    message: string,
    readonly alertRateChangePct: number,
  ) {
    super(message);
    this.name = "RolloutGuardrailError";
  }
}

/**
 * The gate.
 *
 * An agent has no session and no user row, so it cannot produce a `DeployActor`
 * with `role: "ops"`. Anything that is not an ops user — including an agent, a
 * compliance officer and a head of compliance — is refused here before any
 * state is read or written.
 */
export function assertOpsActor(
  actor: DeployActor | null | undefined,
  what: string,
): asserts actor is DeployActor {
  if (!actor || typeof actor.id !== "string" || !actor.id) {
    throw new DeploymentForbiddenError(
      `${what} requires a signed-in operations user. Agents and background jobs cannot deploy.`,
    );
  }
  if (actor.role !== "ops") {
    throw new DeploymentForbiddenError(
      `${what} is restricted to the operations role. You are signed in as ${actor.role}.`,
    );
  }
}

/* -------------------------------------------------------------------------- */
/* Rollout stages and the guardrail                                           */
/* -------------------------------------------------------------------------- */

export const ROLLOUT_STAGES = [10, 50, 100] as const;
export type RolloutStage = (typeof ROLLOUT_STAGES)[number];

/**
 * A shadow rule raising this much more than the live rule blocks a rollout
 * until an operator types a reason. 150% means two and a half times the
 * alerts — far beyond what a team absorbs without planning for it.
 */
export const ALERT_RATE_GUARDRAIL_PCT = 150;

/** Transactions considered by a real (non-simulated) shadow comparison. */
export const SHADOW_WINDOW_DAYS = 30;

/** Synthetic transactions generated by one simulated day. */
export const SIMULATED_TXN_COUNT = 2_000;

/**
 * Whether a customer is on the new rule at a given rollout percentage.
 *
 * A stable hash, not `Math.random()`: a customer must stay on the same side of
 * the rollout for every transaction, and must still be on it after a restart.
 * Exported so the UI can explain the split and tests can reproduce it.
 */
export function isCustomerInRollout(
  customerId: string,
  percent: number,
): boolean {
  if (percent >= 100) return true;
  if (percent <= 0) return false;
  const digest = createHash("sha256").update(customerId).digest();
  return digest.readUInt32BE(0) % 100 < percent;
}

