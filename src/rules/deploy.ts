/* 4. Rollback                                                                */
/* -------------------------------------------------------------------------- */

export interface RollbackResult {
  ruleId: string;
  ruleCode: string;
  rolledBackVersionId: string;
  restoredVersionId: string;
  restoredVersion: number;
}

/** Shortest rollback reason worth keeping in an audit trail. */
export const MIN_ROLLBACK_REASON = 10;

/**
 * Takes the live version out of force and restores the one it replaced.
 *
 * One transaction, so there is never an instant where a rule has no version in
 * force. The reason is mandatory: a rollback with no stated cause is the one
 * entry a regulator will always ask about.
 */
export async function rollback(
  ruleId: string,
  reason: string,
  actor: DeployActor,
): Promise<RollbackResult> {
  assertOpsActor(actor, "Rolling back");

  const trimmed = reason.trim();
  if (trimmed.length < MIN_ROLLBACK_REASON) {
    throw new DeploymentStateError(
      `A rollback reason of at least ${MIN_ROLLBACK_REASON} characters is required.`,
    );
  }

  return txDb.transaction(async (tx) => {
    const [rule] = await tx
      .select({ id: rules.id, code: rules.code })
      .from(rules)
      .where(eq(rules.id, ruleId))
      .limit(1);

    if (!rule) throw new DeploymentStateError(`Rule ${ruleId} does not exist.`);

    const [liveVersion] = await tx
      .select({ id: ruleVersions.id, version: ruleVersions.version })
      .from(ruleVersions)
      .where(
        and(eq(ruleVersions.ruleId, ruleId), eq(ruleVersions.status, "live")),
      )
      .limit(1);

    if (!liveVersion) {
      throw new DeploymentStateError(
        `${rule.code} has no live version to roll back.`,
      );
    }

    // The most recently retired version is the one this live version replaced.
    const [restore] = await tx
      .select({ id: ruleVersions.id, version: ruleVersions.version })
      .from(ruleVersions)
      .where(
        and(eq(ruleVersions.ruleId, ruleId), eq(ruleVersions.status, "retired")),
      )
      .orderBy(desc(ruleVersions.version))
      .limit(1);

    if (!restore) {
      throw new DeploymentStateError(
        `${rule.code} has no retired version to restore, so rolling back would leave it with no rule in force.`,
      );
    }

    const now = new Date();

    await tx
      .update(ruleVersions)
      .set({
        status: "rolled_back",
        rolloutPercent: 0,
        rolledBackAt: now,
        rollbackReason: trimmed,
      })
      .where(eq(ruleVersions.id, liveVersion.id));

    await tx
      .update(ruleVersions)
      .set({ status: "live", rolloutPercent: 100, liveAt: now })
      .where(eq(ruleVersions.id, restore.id));

    await tx
      .update(rules)
      .set({ currentVersionId: restore.id })
      .where(eq(rules.id, ruleId));

    await auditInTx(tx, {
      actor: `user:${actor.email}`,
      action: "rule_version.rolled_back",
      entityType: "rule_versions",
      entityId: liveVersion.id,
      details: {
        rule_id: ruleId,
        rule_code: rule.code,
        rolled_back_version: liveVersion.version,
        restored_version_id: restore.id,
        restored_version: restore.version,
        reason: trimmed,
      },
    });

    return {
      ruleId,
      ruleCode: rule.code,
      rolledBackVersionId: liveVersion.id,
      restoredVersionId: restore.id,
      restoredVersion: restore.version,
    };
  });
}
